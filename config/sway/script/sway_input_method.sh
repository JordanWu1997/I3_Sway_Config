#!/usr/bin/env bash
# ~/.config/sway/script/sway_input_method.sh
# Input method framework for sway: ibus (as on i3) or fcitx5 (recommended on Wayland).
#
# Why the environment file: input methods only reach applications that inherit
# GTK_IM_MODULE / QT_IM_MODULE / XMODIFIERS / GLFW_IM_MODULE. On i3 they came from
# ~/.profile, which sway does not load unless it is started by sway-session (test_v3:
# all four were missing). ~/.config/environment.d/*.conf is imported by the systemd user
# manager, and GDM gives that environment to every session it starts, so the variables
# arrive whichever sway entry is chosen on the login screen.
#
#            ibus                                fcitx5
#   tray     only via XDG_CURRENT_DESKTOP=KDE     StatusNotifierItem (swaybar shows it)
#   native   no (ibus lacks input-method-v2)      yes, input-method-v2 (popups: sway >= 1.10)
#   XWayland XIM / GTK module                     XIM / GTK module
#   kitty    GLFW_IM_MODULE=ibus (X11)            GLFW_IM_MODULE=ibus (fcitx5 speaks ibus)
#
# Usage: sway_input_method.sh start|restart|toggle|status|doctor|use <ibus|fcitx5>|write_env
#   doctor: writes ~/sway_im_doctor.txt (environment of sway/fcitx5/kitty, packages,
#           addons, profile, fcitx5-diagnose) for troubleshooting

SWAY_CONFIG="$HOME/.config/sway/config"
SWAY_SCRIPT="${SWAY_SCRIPT:-$HOME/.config/sway/script}"
I3_SCRIPT="${I3_SCRIPT:-$HOME/.config/i3/script}"
ENV_FILE="${XDG_CONFIG_HOME:-$HOME/.config}/environment.d/60-sway-input-method.conf"
ICON="$HOME/.config/i3/share/64x64/language.png"

current_im () {
    awk '$1 == "set" && $2 == "$default_input_method" {print $3; exit}' "$SWAY_CONFIG"
}
IM=$(current_im); IM=${IM:-ibus}

write_env () {
    local im=$1 gtk qt xmod
    case $im in
        fcitx5) gtk=fcitx qt=fcitx xmod=@im=fcitx ;;
        *)      gtk=ibus  qt=ibus  xmod=@im=ibus ;;
    esac
    mkdir -p "$(dirname "$ENV_FILE")"
    cat > "$ENV_FILE" <<CONF
# Generated by ~/.config/sway/script/sway_input_method.sh ($im). Do not edit by hand:
# run "sway_input_method.sh use ibus|fcitx5" instead. Read at login (systemd user
# manager / GDM) and by sway-session. Under i3, ~/.profile is sourced later and wins.
GTK_IM_MODULE=$gtk
QT_IM_MODULE=$qt
XMODIFIERS=$xmod
GLFW_IM_MODULE=ibus
SDL_IM_MODULE=$gtk
I3_SCRIPT=$HOME/.config/i3/script
SWAY_SCRIPT=$HOME/.config/sway/script
PATH=$HOME/.config/sway/bin:$HOME/.local/bin:$HOME/.config/i3/script:\${PATH}
CONF
}

fcitx5_profile () {
    # keyboard-us + chewing, same engines as i3_languagechanger.sh. Rewritten whenever
    # chewing is missing: fcitx5 creates a keyboard-only profile on its first run, and then
    # Ctrl+Alt+space (fcitx5-remote -t) has nothing to switch to. fcitx5 must not be running
    # (it writes the profile back on exit).
    local profile="$HOME/.config/fcitx5/profile"
    [ -f "$profile" ] && grep -qx 'Name=chewing' "$profile" && return
    [ -f "$profile" ] && cp "$profile" "$profile.bak.$(date +%Y%m%d%H%M%S)"
    mkdir -p "$(dirname "$profile")"
    cat > "$profile" <<'CONF'
[Groups/0]
Name=Default
Default Layout=us
DefaultIM=keyboard-us

[Groups/0/Items/0]
Name=keyboard-us
Layout=

[Groups/0/Items/1]
Name=chewing
Layout=

[GroupOrder]
0=Default
CONF
}

stop_all () {
    pkill -u "$USER" -x ibus-daemon 2>/dev/null
    pkill -u "$USER" -x fcitx5 2>/dev/null
    sleep 0.5
}

start_im () {
    case $IM in
        fcitx5)
            command -v fcitx5 >/dev/null || { notify-send -u critical "Input method" "fcitx5 is not installed (install_sway.sh: input_method_packages)"; exit 1; }
            local ibus_was_running=0
            if pgrep -u "$USER" -x ibus-daemon >/dev/null; then
                pkill -u "$USER" -x ibus-daemon; ibus_was_running=1
            fi
            if pgrep -u "$USER" -x fcitx5 >/dev/null; then
                # Keep it, unless chewing is missing from the profile or ibus-daemon was
                # running too: its ~/.config/ibus/bus address files would keep pointing
                # kitty (GLFW_IM_MODULE=ibus) at the dead ibus socket.
                if [ "$ibus_was_running" = 0 ] && grep -qx 'Name=chewing' "$HOME/.config/fcitx5/profile" 2>/dev/null; then
                    return
                fi
                pkill -u "$USER" -x fcitx5; sleep 0.5
            fi
            fcitx5_profile
            # kitty (GLFW_IM_MODULE=ibus) finds the IM through ~/.config/ibus/bus/*; a stale
            # file from ibus-daemon points it at a dead socket. fcitx5's ibus frontend
            # writes a fresh one when it starts.
            rm -f "$HOME"/.config/ibus/bus/* 2>/dev/null
            setsid -f fcitx5 -d --replace >"${XDG_RUNTIME_DIR:-/tmp}/fcitx5.log" 2>&1
            ;;
        *)
            pgrep -u "$USER" -x fcitx5 >/dev/null && pkill -u "$USER" -x fcitx5
            "$SWAY_SCRIPT/sway_ibus.sh" start
            ;;
    esac
}

proc_env () {   # proc_env <pid> <var...>: selected variables of a running process
    local pid=$1; shift
    tr '\0' '\n' < "/proc/$pid/environ" 2>/dev/null | grep -E "^($(IFS='|'; echo "$*"))=" || echo "    (none of: $*)"
}

doctor () {
    local out="$HOME/sway_im_doctor.txt" pid f
    local vars=(SWAY_SESSION_LAUNCHER GTK_IM_MODULE QT_IM_MODULE XMODIFIERS GLFW_IM_MODULE SDL_IM_MODULE XDG_CURRENT_DESKTOP XDG_SESSION_TYPE WAYLAND_DISPLAY DISPLAY)
    {
        echo "=== sway_input_method.sh doctor  $(date)"
        echo "framework (\$default_input_method): $IM"
        sway --version 2>&1; fcitx5 --version 2>&1 | head -n1; kitty --version 2>&1
        echo; echo "=== login entries"
        for f in /usr/share/wayland-sessions/sway*.desktop /usr/local/share/wayland-sessions/*.desktop; do
            [ -f "$f" ] && echo "$f: $(grep -E '^(Name|Exec)=' "$f" | tr '\n' ' ')"
        done
        command -v dpkg-divert >/dev/null && dpkg-divert --list '*wayland-sessions*'
        ls -l /usr/local/bin/sway-session 2>&1
        echo; echo "=== environment of the running sway"
        for pid in $(pgrep -u "$USER" -x sway); do echo "  sway pid $pid"; proc_env "$pid" "${vars[@]}" | sed 's/^/    /'; done
        echo; echo "=== environment of this shell"
        for f in "${vars[@]}"; do echo "    $f=${!f:-<unset>}"; done
        echo; echo "=== input method daemons"
        for pid in $(pgrep -u "$USER" -x 'fcitx5|ibus-daemon'); do
            echo "  $(ps -o pid=,args= -p "$pid")"; proc_env "$pid" DISPLAY WAYLAND_DISPLAY XDG_CURRENT_DESKTOP | sed 's/^/    /'
        done
        echo; echo "=== kitty processes (need GLFW_IM_MODULE=ibus)"
        for pid in $(pgrep -u "$USER" -x kitty); do echo "  kitty pid $pid"; proc_env "$pid" GLFW_IM_MODULE XMODIFIERS DISPLAY | sed 's/^/    /'; done
        grep -h '^linux_display_server' "$HOME/.config/kitty/"*.conf 2>/dev/null
        echo; echo "=== env file $ENV_FILE"; cat "$ENV_FILE" 2>&1
        echo; echo "=== packages"
        if command -v dpkg >/dev/null; then
            dpkg -l 'fcitx5*' 'ibus*' 2>/dev/null | awk '/^ii/ {print "    " $2, $3}'
        else
            rpm -qa 'fcitx5*' 'ibus*' 2>/dev/null | sed 's/^/    /'
        fi
        echo; echo "=== fcitx5 addons (chewing, ibusfrontend for kitty, xim for XWayland, waylandim, notificationitem = tray)"
        for f in chewing ibusfrontend xim waylandim notificationitem classicui; do
            ls /usr/share/fcitx5/addon/$f.conf >/dev/null 2>&1 && echo "    $f: yes" || echo "    $f: MISSING"
        done
        echo; echo "=== fcitx5 profile"; cat "$HOME/.config/fcitx5/profile" 2>&1
        echo; echo "=== fcitx5-remote"; fcitx5-remote 2>&1; fcitx5-remote -n 2>&1
        echo; echo "=== ~/.config/ibus/bus"; ls -l "$HOME/.config/ibus/bus/" 2>&1; cat "$HOME"/.config/ibus/bus/* 2>/dev/null
        echo; echo "=== fcitx5 log"; tail -n 40 "${XDG_RUNTIME_DIR:-/tmp}/fcitx5.log" 2>&1
        echo; echo "=== fcitx5-diagnose"
        command -v fcitx5-diagnose >/dev/null && fcitx5-diagnose 2>&1 || echo "    fcitx5-diagnose not installed"
    } > "$out" 2>&1
    echo "Report written to $out"
}

case ${1:-status} in
    start)
        # Keep the environment file in step with $default_input_method; it is read at login,
        # so a change only reaches applications after logging out and back in.
        if ! grep -q "sway_input_method.sh ($IM)" "$ENV_FILE" 2>/dev/null; then
            write_env "$IM"
            notify-send -u normal "Input method: $IM" "Input method variables updated for $IM. Log out and back in once so that all applications use $IM." --icon="$ICON"
        fi
        start_im ;;
    restart) stop_all; start_im; notify-send -u low "Input method" "$IM restarted" --icon="$ICON" ;;
    toggle)
        # Follow the daemon that is actually running, not only $default_input_method
        # (test_v6: fcitx5 was running while the config still said ibus, so the ibus
        # switcher ran and nothing changed).
        if pgrep -u "$USER" -x fcitx5 >/dev/null; then
            if ! fcitx5-remote -t 2>/dev/null; then
                notify-send -u normal "fcitx5 Input Method" "fcitx5 does not answer on D-Bus (fcitx5-remote -t failed)" --icon="$ICON"
                exit 1
            fi
            sleep 0.15
            case $(fcitx5-remote -n 2>/dev/null) in
                keyboard-*) name="English (keyboard-us)" ;;
                chewing)    name="Chewing (注音)" ;;
                "")         name="unknown" ;;
                *)          name=$(fcitx5-remote -n) ;;
            esac
            notify-send -u low "fcitx5 Input Method" "Switch to ${name}" --icon="$ICON"
        elif pgrep -u "$USER" -x ibus-daemon >/dev/null; then
            "$I3_SCRIPT/i3_languagechanger.sh"
        else
            notify-send -u normal "Input method" "No input method daemon is running ($IM). Start it: sway_input_method.sh restart" --icon="$ICON"
        fi ;;
    status)
        echo "framework: $IM"
        echo "env file:  $ENV_FILE $( [ -f "$ENV_FILE" ] && echo '(present)' || echo '(missing)')"
        for v in GTK_IM_MODULE QT_IM_MODULE XMODIFIERS GLFW_IM_MODULE; do echo "  $v=${!v:-<unset>}"; done
        pgrep -u "$USER" -ax 'ibus-daemon|fcitx5' || echo "  no input method daemon running" ;;
    use)
        case $2 in
            ibus|fcitx5) ;;
            *) echo "Usage: $0 use ibus|fcitx5"; exit 1 ;;
        esac
        sed -i -E "s/^set \\\$default_input_method .*/set \$default_input_method $2/" "$SWAY_CONFIG"
        IM=$2; write_env "$IM"; stop_all; start_im
        notify-send -u normal "Input method: $IM" "Log out and back in so that all applications get the $IM variables." --icon="$ICON" ;;
    write_env) write_env "$IM"; echo "wrote $ENV_FILE ($IM)" ;;
    doctor) doctor ;;
    *) echo "Usage: $0 start|restart|toggle|status|doctor|use <ibus|fcitx5>|write_env"; exit 1 ;;
esac
