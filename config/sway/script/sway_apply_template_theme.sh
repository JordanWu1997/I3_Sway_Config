#!/usr/bin/env bash
# Ported from i3_apply_template_theme.sh for sway.
# Replaced X11 tools:
#   - xrdb -load ~/.Xresources + i3 set_from_resource -> ~/.cache/wal/colors-sway-i3 written from
#                                                       the template's colors.json ("set $bg/$fg/$c0..$c15"),
#                                                       included by ~/.config/sway/config
#   - i3-msg reload                                   -> swaymsg reload
#   xrdb is still run when available, for XWayland apps that read Xresources.
# Usage is identical: sway_apply_template_theme.sh [template]

SWAY_SCRIPT="${SWAY_SCRIPT:-$HOME/.config/sway/script}"
THEME_TEMPLATE_DIR="$HOME/.config/i3/theme/templates"
WAL_DIR="$HOME/.cache/wal"
SWAY_COLOR_FILE="$WAL_DIR/colors-sway-i3"
FILE_NAME_LIST=( \
    colors \
    colors.sh \
    colors.Xresources \
    colors.json \
    colors-kitty.conf \
    colors-rofi-dark.rasi \
)
ICON="$HOME/.config/i3/share/64x64/paint_palette.png"

show_available_theme_templates () {
    echo Available Templates:
    for THEME in $(command ls -D "${THEME_TEMPLATE_DIR}/"); do
        echo "  $THEME"
    done
}

verify_input_template () {
    if [[ ! -d "${THEME_TEMPLATE_DIR}/$1" ]]; then
        show_available_theme_templates
        false
    else
        true
    fi
}

replace_all_wal_color_files () {
    mkdir -p "${WAL_DIR}"
    # Replace Files
    for file in "${FILE_NAME_LIST[@]}"; do
        echo "${THEME_TEMPLATE_DIR}/$1/${file}"
        command cp "${THEME_TEMPLATE_DIR}/$1/${file}" "${WAL_DIR}/"
    done
}

# Write the sway color variables (same format as the pywal template colors-sway-i3)
generate_sway_color_file () {
    local json="${THEME_TEMPLATE_DIR}/$1/colors.json"
    [[ -f $json ]] || { echo "Missing $json" >&2; return 1; }
    {
        echo "# Generated by sway_apply_template_theme.sh from template '$1'"
        jq -r '
            "set $bg  \(.special.background)",
            "set $fg  \(.special.foreground)",
            (range(0; 16) as $i | "set $c\($i)\(if $i < 10 then "  " else " " end)\(.colors["color\($i)"])")
        ' "$json"
    } > "${SWAY_COLOR_FILE}.tmp" && mv "${SWAY_COLOR_FILE}.tmp" "${SWAY_COLOR_FILE}"
}

reload_after_replacement () {
    # Xresources for XWayland apps (optional on sway)
    if command -v xrdb >/dev/null && [[ -n $DISPLAY && -f ~/.Xresources ]]; then
        xrdb -load ~/.Xresources
    fi
    # Reload sway (re-reads ~/.cache/wal/colors-sway-i3)
    swaymsg reload
    # A reload re-applies the config's "output * bg"; put the current wallpaper back
    [[ -x $SWAY_SCRIPT/sway_wallpaper_operator.sh ]] && "$SWAY_SCRIPT/sway_wallpaper_operator.sh" feh restore_last
    return 0
}

apply_theme () {
    replace_all_wal_color_files "$1"
    generate_sway_color_file "$1" || return 1
    reload_after_replacement
    notify-send -u low "Template Theme" "Theme $1 is applied" --icon="${ICON}"
}

# Main
if [ -z "$1" ]; then
    THEME=$(command ls -D "${THEME_TEMPLATE_DIR}/" | rofi -dmenu -i -p "Theme Templates")
    if [[ -z ${THEME} ]]; then
        exit
    fi
    apply_theme "${THEME}"
else
    if verify_input_template "$1"; then
        apply_theme "$1"
    fi
fi
